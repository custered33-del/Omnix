export function idPrefixFor(type: NodeType): string {
  return ID_PREFIX[type];
}

/** Create a detached node (no parent yet) with default props merged with overrides. */
export function makeNode<T extends NodeType>(
  type: T,
  props: Partial<NodePropsMap[T]> = {},
  id: string = newId(ID_PREFIX[type]),
): SceneNode<T> {
  const defaults = DEFAULT_PROPS[type]() as NodePropsMap[T];
  const merged = { ...defaults } as Record<string, unknown>;
  for (const [k, v] of Object.entries(props)) if (v !== undefined) merged[k] = v;
  return { id, type, parentId: null, children: [], props: merged as NodePropsMap[T] };
}
