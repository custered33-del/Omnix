/**
 * Generates docs/MCP_TOOLS.md and docs/mcp-tools.json from the live tool registry,
 * so the catalog always matches what the server actually exposes.
 *   pnpm catalog
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { z } from 'zod';
import { createOmnix } from '../packages/server/src/app.js';
import '../packages/server/src/modules.js';
import { allTools } from '../packages/server/src/mcp/tools/index.js';
import type { ToolDef } from '../packages/server/src/mcp/registry.js';

const CATEGORY_TITLES: Record<string, string> = {
  project: 'Projects, history and session memory',
  assets: 'Asset library',
  image: 'Image editor',
  video: 'Video editor',
  animation: 'Animation maker',
  code: 'Code Grounds',
  document: 'Documents',
  slides: 'Slideshows',
  ai: 'Generative and AI-native tools',
  agent: 'Autonomous agent runner',
  collaboration: 'Collaboration, versions and batch',
  export: 'Import and export',
};

function schemaOf(tool: ToolDef) {
  return z.toJSONSchema(z.object(tool.input), { io: 'input', unrepresentable: 'any' });
}

function outputSchemaOf(tool: ToolDef) {
  try {
    return z.toJSONSchema(tool.output, { unrepresentable: 'any' });
  } catch {
    return { type: 'object' };
  }
}

const dataDir = await fs.mkdtemp(path.join(os.tmpdir(), 'omnix-catalog-'));
const omnix = await createOmnix({ memory: true, dataDir, webDist: null });
const tools = allTools(omnix.services);
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');

const json = tools.map((t) => ({ name: t.name, title: t.title, category: t.category, access: t.access, description: t.description, inputSchema: schemaOf(t), outputSchema: outputSchemaOf(t), example: t.example }));
await fs.writeFile(path.join(root, 'docs/mcp-tools.json'), JSON.stringify(json, null, 2) + '\n');

const lines: string[] = [];
lines.push('# Omnix MCP tool catalog', '');
lines.push('> Generated by `pnpm catalog` from the live tool registry. Do not edit by hand.', '');
lines.push(`Omnix exposes **${tools.length} tools** over MCP (Streamable HTTP at \`/mcp\`, legacy SSE at \`/sse\`, and stdio via \`pnpm mcp:stdio\`).`);
lines.push('Read tools never change anything. Write tools follow the connection\'s permission mode: in *edit with approval* they create a proposal the user reviews; in *autonomous* they commit directly inside allowed projects. Every call is logged in the activity feed.', '');
lines.push('Read-only resources: `omnix://projects`, `omnix://projects/{projectId}`, `.../tree`, `.../layers/{canvasId}`, `.../timeline/{sequenceId}`, `.../code/{workspaceId}`, `.../document/{documentId}`, `.../slides/{deckId}`, `.../selection`, `.../notes`, `omnix://assets`.', '');
lines.push('## Contents', '');
const byCat = new Map<string, ToolDef[]>();
for (const t of tools) byCat.set(t.category, [...(byCat.get(t.category) ?? []), t]);
for (const [cat, list] of byCat) lines.push(`- [${CATEGORY_TITLES[cat] ?? cat}](#${(CATEGORY_TITLES[cat] ?? cat).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/-$/, '')}) (${list.length})`);
lines.push('');
for (const [cat, list] of byCat) {
  lines.push(`## ${CATEGORY_TITLES[cat] ?? cat}`, '');
  for (const t of list) {
    lines.push(`### \`${t.name}\``, '');
    lines.push(`**${t.title}** · ${t.access === 'read' ? 'read-only' : 'write'}`, '');
    lines.push(t.description, '');
    lines.push('<details><summary>Input schema</summary>', '', '```json', JSON.stringify(schemaOf(t), null, 2), '```', '', '</details>', '');
    lines.push('<details><summary>Output schema</summary>', '', '```json', JSON.stringify(outputSchemaOf(t), null, 2), '```', '', '</details>', '');
    lines.push('Example call:', '', '```json', JSON.stringify({ name: t.name, arguments: t.example.input }, null, 2), '```', '');
    if (t.example.output !== undefined) lines.push('Example result (structured content):', '', '```json', JSON.stringify(t.example.output, null, 2), '```', '');
  }
}
await fs.writeFile(path.join(root, 'docs/MCP_TOOLS.md'), lines.join('\n'));
await omnix.close();
await fs.rm(dataDir, { recursive: true, force: true });
console.log(`Wrote ${tools.length} tools to docs/MCP_TOOLS.md and docs/mcp-tools.json`);
